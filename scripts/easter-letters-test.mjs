import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'https://example.test/' });
globalThis.window = dom.window;
globalThis.document = dom.window.document;
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const { default: React, act } = await import('react');
const { createRoot } = await import('react-dom/client');
const { default: NameLetters } = await import('../src/motion/NameLetters.jsx');
const root = createRoot(document.getElementById('root'));
await act(async () => root.render(React.createElement(React.StrictMode, null, React.createElement(NameLetters))));
const heading = document.getElementById('hero-title');
assert.equal(heading.getAttribute('aria-label'), 'Tim Wang');
assert.equal(heading.textContent, 'TimWang');
assert.deepEqual([...heading.children].map(node => node.tagName), ['SPAN', 'EM']);
const letters = [...heading.querySelectorAll('button')];
assert.equal(letters.length, 7);
assert.ok(letters.every(button => button.type === 'button' && button.getAttribute('aria-label').includes('Change typeface')));
await act(async () => letters[0].click());
assert.deepEqual(letters.map(node => node.dataset.font), ['1', '0', '0', '0', '0', '0', '0']);
assert.equal(letters[0].querySelector('span').dataset.flip, 'true');
await act(async () => { letters[0].click(); letters[4].click(); });
assert.deepEqual(letters.map(node => node.dataset.font), ['2', '0', '0', '0', '1', '0', '0']);
await act(async () => letters[0].click());
assert.equal(letters[0].dataset.font, '0');
// JSDOM supplies the detail=0 click which native buttons emit for Enter/Space.
await act(async () => letters[1].dispatchEvent(new window.MouseEvent('click', { bubbles: true, detail: 0 })));
assert.equal(letters[1].dataset.font, '1');
assert.ok([...heading.children].every(node => !node.getAttribute('style')), 'No parent transform changes');
const css = readFileSync(new URL('../src/motion/NameLetters.css', import.meta.url), 'utf8');
assert.match(css, /\.name-letter::before\s*\{[^}]*content:attr\(data-letter\);[^}]*visibility:hidden;/);
assert.match(css, /\.name-letter-glyph\s*\{[^}]*position:absolute;/);
assert.match(css, /prefers-reduced-motion:reduce[^]*animation:none;/);
await act(async () => root.unmount());
dom.window.close();
console.log('PASS: independent name fonts, keyboard-origin clicks, stable layout structure and reduced-motion styles.');
